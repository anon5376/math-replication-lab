"""Reproduce the arithmetic for ranks 0 through 52. Python 3.10+, standard library."""

import argparse
from fractions import Fraction
from math import comb, gcd
from pathlib import Path
import subprocess


def paper_counts(limit):
    """Return (all, first-maximum, other) using the subtraction-free recurrence."""
    counts = [([1], [], []), ([1], [1], [])]

    def trimmed(row):
        while row and row[-1] == 0:
            row.pop()
        return row

    for n in range(2, limit + 1):
        prior, prior_first, prior_other = counts[-1]
        first, other = [0] * n, [0] * n
        for k, count in enumerate(prior_first):
            first[k] += count
        for k, count in enumerate(prior_other):
            first[k + 1] += count
        for k, count in enumerate(prior):
            other[k] += count
        for left in range(1, n - 1):
            for i, u in enumerate(counts[left][0]):
                for j, v in enumerate(counts[n - 1 - left][0]):
                    other[i + j + 1] += u * v
        total = [a + c for a, c in zip(first, other)]
        counts.append((trimmed(total), trimmed(first), trimmed(other)))
    return counts[:limit + 1]


def paper_rows(limit):
    return [row for row, _, _ in paper_counts(limit)]


def insertion_rows(limit):
    """Independent enumeration by inserting a new minimum in the increasing suffix."""
    rows = [[1], [1]]
    states = {(1, "absent", 0): 1}
    for _n in range(2, limit + 1):
        following = {}

        def add(length, boundary, drops, count):
            key = (length, boundary, drops)
            following[key] = following.get(key, 0) + count

        for (length, boundary, drops), count in states.items():
            # Just before the old minimum, a former unit drop becomes big.
            new_boundary = "absent" if boundary == "absent" else "big"
            add(length + 1, new_boundary, drops + (boundary == "unit"), count)
            # Immediately after it, the new boundary is the unit drop.
            add(length, "unit", drops, count)
            # Deeper in the increasing suffix, the new boundary is big.
            for new_length in range(1, length):
                add(new_length, "big", drops + 1, count)
        states = following
        row = [0] * (1 + max(d for _, _, d in states))
        for (_, _, drops), count in states.items():
            row[drops] += count
        rows.append(row)
    return rows[: limit + 1]


def numerator(row, a, b):
    """b^degree B(-a/b), using integer Horner evaluation."""
    value = row[-1]
    scale = 1
    for c in reversed(row[:-1]):
        scale *= b
        value = -a * value + c * scale
    return value


def witnesses(row):
    """Return degree many positive rational magnitudes with alternating signs."""
    degree = len(row) - 1
    if degree == 0:
        return []
    result = []
    sign = 1
    for exponent in range(-24, 25):
        for mantissa in range(32, 64):
            a = mantissa << max(0, exponent)
            b = 32 << max(0, -exponent)
            common = gcd(a, b)
            a, b = a // common, b // common
            if sign * numerator(row, a, b) < 0:
                result.append(Fraction(a, b))
                sign = -sign
                if len(result) == degree:
                    return result
    raise ValueError(f"insufficient sign changes in degree {degree}")


def lean_data(counts, grids):
    lines = [
        "import BigDescents132.Coefficients",
        "",
        "/-! Finite certificate data generated by `python3 replay52.py --write-data`.",
        "All coefficient rows, degrees and rational sign intervals are checked in Through52. -/",
        "",
        "namespace BigDescents132.Certificate52",
        "",
        "def table : ℕ → Coefficients.Counts",
    ]
    for n, (row, first, other) in enumerate(counts):
        lines.extend([f"  | {n} => ⟨{row},", f"      {first},", f"      {other}⟩"])
    lines.extend(["  | _ => default", "", "def grid : ℕ → List ℚ"])
    for n, grid in enumerate(grids):
        lines.append(f"  | {n} => {lean_grid(grid)}")
    return "\n".join([*lines, "  | _ => []", "", "end BigDescents132.Certificate52", ""])


def lean_grid(grid):
    return "[" + ", ".join(f"(-{p.numerator}/{p.denominator} : ℚ)" for p in grid) + "]"


def lean_source(rows, grids):
    # First identify each literal coefficient list with the permutation sum.
    lines = [
        "import BigDescents132.Through52",
        "open BigDescents132",
        "namespace Replay52",
        "set_option maxRecDepth 100000",
        "set_option maxHeartbeats 1000000",
    ]
    for n, (row, grid) in enumerate(zip(rows, grids)):
        xs = lean_grid(grid)
        lines.extend([
            f"theorem coefficients{n} : B {n} = ofRow {row} := B_eq_row_through52 {n} (by decide)",
            f"theorem row{n} : (B {n}).natDegree = {len(grid)} ∧ SimpleNegative (B {n}) := by",
            f"  rw [coefficients{n}]",
            f"  exact checked_row _ {xs} (by decide +kernel) (by decide) (by decide +kernel)",
            f"#print axioms row{n}",
        ])
    return "\n".join([*lines, "end Replay52", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--lean", action="store_true", help="replay each exact coefficient list and rational certificate for B n")
    parser.add_argument("--write-data", action="store_true", help="regenerate the tracked Lean certificate data")
    args = parser.parse_args()
    counts = paper_counts(52)
    rows = [row for row, _, _ in counts]
    if rows != insertion_rows(52):
        raise ValueError("the two enumeration methods disagree")
    grids = []
    for n, row in enumerate(rows):
        if sum(row) != comb(2 * n, n) // (n + 1) or row[0] <= 0:
            raise ValueError(f"incorrect total or constant coefficient at rank {n}")
        if len(row) - 1 != 2 * max(0, n - 1) // 3:
            raise ValueError(f"incorrect degree at rank {n}")
        grids.append(witnesses(row))
    print(f"n=0..52: 53 equal coefficient rows, {sum(map(len, grids))} exact negative-root intervals", flush=True)
    data = Path(__file__).resolve().parent / "BigDescents132" / "Data52.lean"
    source = lean_data(counts, grids)
    if args.write_data:
        data.write_text(source, encoding="utf-8")
    if data.read_text(encoding="utf-8") != source:
        raise ValueError("Data52.lean differs from the reproduced coefficient rows or sign witnesses")
    if args.lean:
        subprocess.run(
            ["lake", "env", "lean", "--stdin"], cwd=Path(__file__).resolve().parent,
            input=lean_source(rows, grids), text=True, check=True,
        )


if __name__ == "__main__":
    main()
